    CAST(NULL AS STRING) AS DISTRICT_MUNICIPALITY,
    CAST(NULL AS STRING) AS METROPOLITAN_MUNICIPALITY,
    CAST(NULL AS STRING) AS CITY,
    INITCAP(TRIM(PRACTICE_NAME)) AS PRACTICE_NAME,
    TRIM(PRACTICE_NUM) AS PRACTICE_NUM,
    'Pharmacy' AS PRACTICE_TYPE,
    INITCAP(TRIM(ARRAY_TO_STRING(
        [NULLIF(TRIM(ADDRESS), ''), NULLIF(TRIM(SUBURB), ''), NULLIF(TRIM(CITY), '')],
        ', '
    ))) AS ADDRESS,
    TRIM(PHONE) AS PHONE,
    'Private' AS FUNDING,
    'GEMS' AS COMPANY,
    CAST(NULL AS GEOGRAPHY) AS COORDS
FROM RAW.PHARMACIES_GEMS_GAUTENG
WHERE PRACTICE_NAME IS NOT NULL
  AND TRIM(PRACTICE_NAME) != ''

