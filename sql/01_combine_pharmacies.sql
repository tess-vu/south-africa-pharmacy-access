-- Builds INTERMEDIATE.PHARMACIES_COMBINED from eight RAW medical-aid network tables.
-- Municipality and city columns stay NULL pending geocoding verification.
-- Contract: PHARMACY_ID, PROVINCE, LOCAL_MUNICIPALITY, DISTRICT_MUNICIPALITY,
--           METROPOLITAN_MUNICIPALITY, CITY, PRACTICE_NAME, PRACTICE_NUM,
--           PRACTICE_TYPE, ADDRESS, PHONE, FUNDING, COMPANY, COORDS (GEOGRAPHY)

