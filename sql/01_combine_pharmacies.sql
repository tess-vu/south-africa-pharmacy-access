-- CONSERVATIVE DEDUPLICATION USING PRACTICE_NUM
-- Dedupes on PRACTICE_NUM + COMPANY, keeping the longest ADDRESS.
-- Rows with NULL PRACTICE_NUM are all kept for spatial dedup post-geocoding.
-- Assigns PHARMACY_ID here.
CREATE OR REPLACE TABLE INTERMEDIATE.PHARMACIES_COMBINED AS
SELECT
    ROW_NUMBER() OVER (ORDER BY PROVINCE, PRACTICE_NAME, COMPANY) AS PHARMACY_ID,
    PROVINCE,
    LOCAL_MUNICIPALITY,
    DISTRICT_MUNICIPALITY,
    METROPOLITAN_MUNICIPALITY,
    CITY,
    PRACTICE_NAME,
    PRACTICE_NUM,
    PRACTICE_TYPE,
    ADDRESS,
    PHONE,
    FUNDING,
    COMPANY,
    COORDS
FROM (
    SELECT
        *,
        CASE
            WHEN PRACTICE_NUM IS NOT NULL THEN
                ROW_NUMBER() OVER (
                    PARTITION BY PRACTICE_NUM, COMPANY
                    ORDER BY LENGTH(ADDRESS) DESC, PRACTICE_NAME
                )
            ELSE 1
        END AS row_num
    FROM INTERMEDIATE.PHARMACIES_COMBINED
) t
WHERE row_num = 1;


DELETE FROM INTERMEDIATE.PHARMACIES_COMBINED
WHERE ADDRESS IS NULL
  AND PRACTICE_NUM IS NULL;


-- VALIDATION
SELECT PROVINCE, COUNT(*) AS RECORD_COUNT
FROM INTERMEDIATE.PHARMACIES_COMBINED
GROUP BY PROVINCE;

SELECT COMPANY, COUNT(*) AS RECORD_COUNT
FROM INTERMEDIATE.PHARMACIES_COMBINED
GROUP BY COMPANY
ORDER BY RECORD_COUNT DESC;

SELECT
    IF(PRACTICE_NUM IS NOT NULL, 'Has PRACTICE_NUM', 'NULL PRACTICE_NUM') AS PRACTICE_NUM_STATUS,
    COUNT(*) AS RECORD_COUNT
